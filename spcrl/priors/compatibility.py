"""Prior-evidence compatibility: does the admissibility relation predict
observed dependence?

Motivation
----------
Section 2.10 found a structural prior that was correct *as a call graph* and
harmful *as a prior for observational causal dependence*, because the dependence
in that deployment was generated by a shared workload driver the call graph does
not represent. Neither of the prior-quality axes the paper had measured
(corruption, coarseness) can express that defect: both perturb edges *within*
the relation the prior and the data share, whereas here the two relations are
different objects.

This module defines a statistic that can be computed from the data and the prior
alone, with no access to the true graph, so that it is computable on a real
deployment as well as on a benchmark.

Definition
----------
For every ordered pair (i, j), i != j, let

    a_ij = 1 if the prior admits a relation between i and j in either direction
    r_ij = a measure of observed marginal dependence between X_i and X_j

and let AUC be the probability that a randomly chosen admissible pair has a
higher dependence than a randomly chosen inadmissible pair (the Mann-Whitney
statistic). Then

    C = max(0, 2 * AUC - 1)

so that C = 0 when admissibility tells nothing about which variables are
dependent, and C = 1 when every admissible pair is more dependent than every
inadmissible one. C is invariant to monotone rescaling of the dependence
measure, needs no threshold, and has no free parameters.

C is *not* a measure of prior correctness. A prior can be entirely correct about
the mechanism and still score C = 0 if the observed dependence is dominated by a
common driver it does not describe; and a prior can score high while pointing
the wrong way on every edge, because C ignores direction. It measures one thing:
whether the relation the prior describes is the relation the data realise.
"""
from __future__ import annotations
import numpy as np


def _standardise(X: np.ndarray) -> np.ndarray:
    mu, sd = X.mean(0), X.std(0)
    sd = np.where(sd < 1e-12, 1.0, sd)
    return (X - mu) / sd


def dependence_matrix(X: np.ndarray, kind: str = "abs_corr") -> np.ndarray:
    """Symmetric, non-negative dependence between every pair of variables.

    kind:
      "abs_corr"     |Pearson correlation| on standardised data
      "abs_pcorr"    |partial correlation| from the (regularised) precision
                     matrix; sharper but needs T >> d
    """
    Z = _standardise(np.asarray(X, float))
    C = np.corrcoef(Z.T)
    C = np.nan_to_num(C, nan=0.0, posinf=0.0, neginf=0.0)
    if kind == "abs_corr":
        R = np.abs(C)
    elif kind == "abs_pcorr":
        d = C.shape[0]
        P = np.linalg.pinv(C + 1e-3 * np.eye(d))
        dg = np.sqrt(np.clip(np.diag(P), 1e-12, None))
        R = np.abs(-P / np.outer(dg, dg))
    else:
        raise ValueError(kind)
    np.fill_diagonal(R, 0.0)
    return R


def compatibility(S: np.ndarray, X: np.ndarray, kind: str = "abs_corr",
                  live_only: bool = True) -> dict:
    """Prior-evidence compatibility C, plus the quantities it is built from.

    live_only drops variables with no variation in X: a channel that never moves
    carries no dependence information and would otherwise dilute both groups
    (16 of the 40 channels in the Kubernetes campaign are such counters).
    """
    X = np.asarray(X, float)
    S = np.asarray(S, float)
    d = X.shape[1]
    idx = np.arange(d)
    if live_only:
        sd = X.std(0)
        idx = idx[sd >= 1e-12]
    if len(idx) < 3:
        return {"C": float("nan"), "auc": float("nan"), "n_admissible": 0,
                "n_inadmissible": 0, "n_live": int(len(idx))}
    R = dependence_matrix(X[:, idx], kind)
    Ssub = S[np.ix_(idx, idx)]
    adm = (Ssub > 0.5) | (Ssub.T > 0.5)
    iu = np.triu_indices(len(idx), 1)
    r, a = R[iu], adm[iu]
    n1, n0 = int(a.sum()), int((~a).sum())
    if n1 == 0 or n0 == 0:
        return {"C": float("nan"), "auc": float("nan"), "n_admissible": n1,
                "n_inadmissible": n0, "n_live": int(len(idx))}
    # Mann-Whitney AUC via rank sums, with ties handled by average ranks.
    order = np.argsort(r)
    ranks = np.empty(len(r), float)
    ranks[order] = np.arange(1, len(r) + 1)
    # average ranks within ties
    uniq, inv, counts = np.unique(r, return_inverse=True, return_counts=True)
    if (counts > 1).any():
        sums = np.zeros(len(uniq))
        np.add.at(sums, inv, ranks)
        ranks = (sums / counts)[inv]
    auc = (ranks[a].sum() - n1 * (n1 + 1) / 2) / (n1 * n0)
    return {"C": float(max(0.0, 2 * auc - 1)), "auc": float(auc),
            "n_admissible": n1, "n_inadmissible": n0, "n_live": int(len(idx)),
            "mean_dep_admissible": float(r[a].mean()),
            "mean_dep_inadmissible": float(r[~a].mean())}
